import { askKiki } from "@/lib/kiki";
import { selfStatus } from "@/lib/kiki-agent";
import type { Handler } from "../types";

/**
 * Vex ประเมินตัวเอง (เจ้าของสั่ง 6 ส.ค. 2026: "มันไม่รู้จักการพัฒนาตัวเอง")
 *
 * เคสจริงที่พัง 2 รอบในวันเดียว เมื่อถูกถามว่า
 * *"คิดว่าตัวเองมีอะไรอีกมั้ย ที่คิดว่าตัวเองไม่เก่ง และทำได้ไม่ดีพอ"*
 *  รอบแรก → ตอบด้วย "การ์ดการเงินส่วนตัว" (ไปเข้าเส้นทางเงิน คนละเรื่องกันเลย)
 *  รอบสอง → ตอบว่า *"ช่วยระบุสเปกให้ชัดเจนหน่อยครับว่าต้องการเพิ่มอะไรบ้าง"*
 *           ทั้งที่เจ้าของกำลัง "ถามความเห็นของมัน" ไม่ได้สั่งให้ไปทำอะไร
 *
 * ตัวนี้ต้องตอบจากของจริงเสมอ: ความสามารถที่มี · งานที่จดว่ายังค้าง · สิ่งที่เพิ่งแก้ไป
 * ห้ามตอบแบบถ่อมตัวลอย ๆ และห้ามถามกลับ
 */
export const selfReflectHandler: Handler = async (ctx) => {
  const { text, replyText, msgId, is, reply } = ctx;
  if (!is("self_reflect")) return null;

  const status = await selfStatus().catch(() => "");
  const answer = await askKiki(
    `[เจ้าของถามความเห็นเกี่ยวกับตัวคุณเอง] เขาพูดว่า: """${text.slice(0, 500)}"""` +
      `${replyText ? `\n(reply ถึง: """${replyText.slice(0, 600)}""")` : ""}\n\n` +
      `=== สถานะจริงของคุณตอนนี้ (อ่านจากระบบจริง ไม่ใช่ความรู้สึก) ===\n${status}\n\n` +
      `ตอบคำถามเขาตรง ๆ จากข้อมูลข้างบนนี้เท่านั้น\n` +
      `- ชี้จุดที่ตัวเองยัง "ทำได้ไม่ดีพอ" จริง ๆ โดยอ้างของที่จับต้องได้ (ความสามารถที่ยังไม่มี · งานที่จดว่าค้าง · บั๊กที่เพิ่งเจอ)\n` +
      `- แต่ละข้อบอกด้วยว่า "มันทำให้โด้เสียอะไร" ไม่ใช่แค่บอกว่าขาด\n` +
      `- เรียงจากที่กระทบเขามากที่สุดลงมา · เขียนบรรทัดละข้อ\n` +
      `- ปิดท้ายด้วยข้อที่คิดว่าควรทำก่อนเป็นอันดับแรก พร้อมเหตุผล แล้วบอกว่าสั่ง "พัฒนา: ..." ได้เลยถ้าเอา\n` +
      `- ห้ามถ่อมตัวลอย ๆ ห้ามถามกลับว่าอยากได้อะไร ห้ามยกเรื่องที่ไม่มีในข้อมูลข้างบนมาแต่ง`,
  ).catch(() => null);

  if (!answer) return null; // ตอบไม่ได้ = ปล่อยให้เส้นทางคุยปกติรับไป ดีกว่าเงียบ
  return reply([{ kind: "text", text: answer, replyTo: msgId }]);
};
