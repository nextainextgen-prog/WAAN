import { askExtractor, getSetting, setSetting, listOwnerFacts } from "./kiki";
import { db } from "./db";

/**
 * โปรไฟล์เจ้าของที่ "ใช้ตัดสินใจได้" (D2 — เจ้าของสั่ง 5 ส.ค. 2026)
 *
 * ปัญหาของเดิม: `ownerFactsContext()` ฉีดข้อเท็จจริงดิบทั้งกอง
 * ซึ่งพอดูของจริงในฐานข้อมูลแล้วส่วนใหญ่เป็นประโยคลอย ๆ ว่า "เขาต้องการให้ AI ..."
 * (11 ข้อในหมวดเป้าหมาย เกือบทั้งหมดพูดถึงพฤติกรรมของ AI ไม่ใช่ตัวเจ้าของ)
 * → เอาไปตัดสินใจแทนเขาไม่ได้เลย เช่น เลือกของให้ไม่ได้ ตอบว่าซื้อไหวไหมไม่ได้
 *
 * ชั้นนี้กลั่นของดิบ + บทสนทนาจริง + ตัวเลขจริง ให้เหลือเฉพาะ "สิ่งที่เปลี่ยนคำตอบ":
 * เป้าหมายตอนนี้ · เพดานเงิน · รสนิยมเวลาเลือกของ · ข้อห้าม · จังหวะชีวิต
 *
 * กติกาที่ห้ามฝืน: **ต้องแยกว่าอันไหนเจ้าของบอกเอง อันไหนเราอนุมานเอง**
 * ไม่งั้นข้อสันนิษฐานจะกลายเป็น "ข้อเท็จจริง" แล้วถูกเอาไปตัดสินใจผิด ๆ ต่อ
 */

const KEY = "vex_owner_profile";
const AT_KEY = "vex_owner_profile_at";
const FRESH_MS = 12 * 3600_000; // เกินนี้ถือว่าเก่า — สร้างใหม่เบื้องหลัง ไม่ให้เจ้าของรอ

const SYSTEM = `กลั่น "โปรไฟล์ที่ใช้ตัดสินใจแทนเจ้าของได้" จากข้อมูลดิบที่ให้มา

เขียนเป็นหัวข้อสั้น ๆ ตามนี้ (หัวข้อไหนไม่มีข้อมูลจริงให้ข้ามไปเลย ห้ามเติมให้ครบ):
เป้าหมายตอนนี้ — สิ่งที่เขากำลังไล่ล่าจริง ๆ ช่วงนี้ ไม่ใช่เป้าหมายลอย ๆ
เพดานเงิน — กรอบงบ พฤติกรรมใช้เงิน จุดที่เขาระวัง/ไม่ระวัง
รสนิยมเวลาเลือกของ — เอาถูก เอาทน เอาแบรนด์ เอาเร็ว เกลียดอะไร
ข้อห้าม — สิ่งที่เขาเคยบอกว่าไม่เอา/อย่าทำ
จังหวะชีวิต — เวลาที่ยุ่ง งานที่แบกอยู่ อะไรกำลังกดดันเขา
เครื่องมือ/ของที่ใช้อยู่ — เครื่อง อุปกรณ์ บริการ ที่รู้แน่ว่าเขามี

กติกาเด็ดขาด
- **ขึ้นต้นด้วยหัวข้อแรกทันที** ห้ามมีคำนำ ห้ามแนะนำตัว ห้ามเขียนว่า "นี่คือโปรไฟล์ของ..."
  (บล็อกนี้ถูกฉีดเข้าไปในหัวสมองของเลขาโดยตรง คำนำจะกลายเป็นเสียงแปลกปลอมในคำตอบ)
- ห้ามเรียกเจ้าของว่า "ท่าน" หรือสรรพนามอื่นใด — เขียนเป็นข้อมูลล้วน ไม่ต้องมีคนพูด
- ห้ามใช้ markdown (** ## - *) เขียนหัวข้อเป็นข้อความล้วน รายการขึ้นต้นด้วย "· "
- ทุกบรรทัดต้องมาจากข้อมูลที่ให้มาจริง ห้ามแต่งขึ้นเอง
- แยกให้ชัดว่าอันไหน "เจ้าของบอกเอง" อันไหน "อนุมานจากพฤติกรรม" — อนุมานให้ขึ้นต้นด้วย (เดา)
- ตัดข้อความประเภท "เขาต้องการให้ AI ทำ X" ทิ้งทั้งหมด นั่นคือคำสั่งถึงระบบ ไม่ใช่ข้อมูลตัวเขา
- ตัวเลขต้องยกมาตรง ๆ ห้ามปัด
- สั้นเข้าไว้ รวมทั้งหมดไม่เกิน 25 บรรทัด บรรทัดละเรื่อง`;

async function rawMaterial(): Promise<string> {
  const parts: string[] = [];

  const facts = (await listOwnerFacts().catch(() => [])).filter((f) => f.category !== "กฎของ Vex");
  if (facts.length) parts.push(`[ข้อเท็จจริงที่สั่งให้จำไว้]\n${facts.map((f) => `- (${f.category}) ${f.fact}`).join("\n")}`);

  // ตัวเลขจริง สำคัญกว่าคำบรรยาย — ใช้ตอบว่า "ซื้อไหวไหม" ได้จริง
  try {
    const { financeSnapshot, snapshotFacts } = await import("./kiki-finance");
    parts.push(`[การเงินจริงเดือนนี้]\n${snapshotFacts(await financeSnapshot()).join("\n")}`);
  } catch { /* ไม่มีข้อมูลเงินก็ข้าม */ }

  try {
    const { tasksContext } = await import("./kiki-tasks");
    const t = await tasksContext();
    if (t) parts.push(`[งานที่ค้างอยู่]\n${t}`);
  } catch { /* ข้าม */ }

  // บทสนทนาช่วงหลัง — ที่มาของรสนิยม/ข้อห้ามจริง ๆ มักอยู่ตรงนี้ ไม่ได้อยู่ในข้อเท็จจริงที่สั่งจำ
  try {
    const rows = await db.kikiChat.findMany({
      where: { role: "user", scope: "owner", createdAt: { gte: new Date(Date.now() - 21 * 86_400_000) } },
      orderBy: { createdAt: "desc" },
      take: 220,
      select: { content: true },
    });
    if (rows.length) parts.push(`[สิ่งที่เจ้าของพิมพ์เองช่วง 3 สัปดาห์]\n${rows.map((r) => `- ${r.content.slice(0, 200)}`).join("\n").slice(0, 22_000)}`);
  } catch { /* ข้าม */ }

  return parts.join("\n\n");
}

/** สร้างโปรไฟล์ใหม่จากของจริง — คืนข้อความโปรไฟล์ (ว่าง = สร้างไม่ได้) */
export async function buildProfile(): Promise<string> {
  const raw = await rawMaterial();
  if (raw.trim().length < 80) return "";
  try {
    const out = await askExtractor(raw.slice(0, 60_000), { system: SYSTEM, timeoutMs: 90_000 });
    const t = out.trim();
    if (!t) return "";
    await setSetting(KEY, t.slice(0, 6000));
    await setSetting(AT_KEY, String(Date.now()));
    return t;
  } catch {
    return "";
  }
}

/**
 * บล็อกโปรไฟล์สำหรับฉีดเข้าบริบท — ต้องเร็วเสมอ ห้ามให้เจ้าของรอ
 * เก่าแล้วก็คืนของเก่าไปก่อน แล้วสร้างใหม่เบื้องหลัง (ของเก่ายังดีกว่าไม่มี)
 */
export async function profileContext(): Promise<string> {
  const [cached, at] = await Promise.all([getSetting(KEY), getSetting(AT_KEY)]);
  if (cached && Date.now() - Number(at || 0) <= FRESH_MS) return wrap(cached);

  // สร้างใหม่ "เบื้องหลังเสมอ" ไม่ว่าจะมีของเก่าหรือไม่ — วัดจริงแล้วใช้เวลา ~109 วินาที
  // ถ้าสร้างสด ๆ ตอนเจ้าของถาม เขาจะนั่งรอเกือบสองนาทีโดยไม่รู้ว่ารออะไรอยู่
  // รอบแรกสุดจึงยอมไม่มีโปรไฟล์ (ตอบจากข้อเท็จจริงดิบไปก่อน) แล้วรอบถัดไปค่อยมีให้ใช้
  if (!building) {
    building = true;
    void buildProfile().catch(() => {}).finally(() => { building = false; });
  }
  return cached ? wrap(cached) : "";
}

let building = false; // กันสร้างซ้อนกันตอนข้อความเข้ามาติด ๆ

function wrap(body: string): string {
  return `=== โปรไฟล์เจ้าของ (กลั่นจากข้อมูลจริง ใช้ประกอบการตัดสินใจแทนเขา) ===
${body}

วิธีใช้: เอาไปเลือก/ฟันธง/เตือนแทนเขาได้เลย — บรรทัดที่ขึ้นต้นด้วย (เดา) คือข้อสันนิษฐาน
ถ้าจะใช้บรรทัดนั้นตัดสินใจเรื่องใหญ่ ให้บอกเขาด้วยว่าเดามาจากอะไร`;
}
